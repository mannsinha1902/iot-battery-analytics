from __future__ import annotations

import pandas as pd
import plotly.express as px
import streamlit as st

from battery_analytics.analytics import (
    calculate_observed_discharge_rates,
    query_device_type_summary,
)
from battery_analytics.data import generate_sensor_data
from battery_analytics.model import predict_remaining_hours, train_life_model


st.set_page_config(page_title="IoT Battery Performance Analytics", layout="wide")
st.title("IoT Device Battery Performance Analytics")
st.caption(
    "Synthetic telemetry-driven dashboard for battery health, usage trends, and remaining-life forecasting."
)


@st.cache_data
def load_dataset() -> pd.DataFrame:
    return generate_sensor_data(n_devices=120, days=14, interval_hours=6, seed=42)


data = load_dataset()
model = train_life_model(data)
summary = query_device_type_summary(data)
discharge = calculate_observed_discharge_rates(data)

predicted = predict_remaining_hours(model, data)
perf_df = data.copy()
perf_df["predicted_remaining_life_hours"] = predicted

st.subheader("Operational overview")
col1, col2, col3, col4 = st.columns(4)
col1.metric("Devices", f"{data['device_id'].nunique()}")
col2.metric("Avg battery", f"{data['battery_pct'].mean():.1f}%")
col3.metric("Avg remaining life", f"{data['remaining_life_hours'].mean():.1f}h")
col4.metric("Model R²", f"{model.metrics['r2']:.3f}")

st.subheader("Battery health by device type")
with st.container():
    summary_cols = [
        "device_type",
        "device_count",
        "avg_battery_pct",
        "avg_remaining_life_hours",
        "avg_temperature_c",
    ]
    st.dataframe(summary[summary_cols], use_container_width=True, hide_index=True)

st.subheader("Trend view")
trend_df = (
    data.groupby(["device_type", "timestamp"], as_index=False)["battery_pct"].mean()
    .sort_values(["device_type", "timestamp"])
)
fig_line = px.line(
    trend_df,
    x="timestamp",
    y="battery_pct",
    color="device_type",
    title="Average battery percentage over time by device type",
)
st.plotly_chart(fig_line, use_container_width=True)

st.subheader("Battery-life forecast")
forecast_df = (
    data.groupby("device_type", as_index=False)["remaining_life_hours"]
    .mean()
    .sort_values("remaining_life_hours")
)
forecast_chart = px.bar(
    forecast_df,
    x="device_type",
    y="remaining_life_hours",
    color="device_type",
    title="Observed average remaining-life hours by device type",
)
st.plotly_chart(forecast_chart, use_container_width=True)

st.subheader("Discharge-rate analysis")
discharge_hist = px.histogram(
    discharge,
    x="discharge_rate_pct_per_hour",
    color="device_type",
    nbins=35,
    title="Observed discharge rate distribution",
)
st.plotly_chart(discharge_hist, use_container_width=True)

st.subheader("Model performance")
metric_cols = ["mae_hours", "rmse_hours", "r2"]
metric_df = pd.DataFrame(
    [{"metric": key, "value": float(value)} for key, value in model.metrics.items()]
)
st.bar_chart(metric_df.set_index("metric"), use_container_width=True)

st.subheader("Exploration")
selected_device = st.selectbox("Choose a device", sorted(data["device_id"].unique()))
selected_rows = data[data["device_id"] == selected_device].sort_values("timestamp")
selected_rows["predicted_remaining_life_hours"] = predict_remaining_hours(
    model, selected_rows
)

selected_chart = px.line(
    selected_rows,
    x="timestamp",
    y=["battery_pct", "predicted_remaining_life_hours"],
    title=f"Battery trend vs. model prediction for {selected_device}",
)
st.plotly_chart(selected_chart, use_container_width=True)

st.caption("This dashboard uses reusable synthetic telemetry generated by the project package, not private or employer-owned data.")
